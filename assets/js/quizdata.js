/** answers：14 個選項索引（0–3）→ 計分結果 */
export function scoreAbility(answers) {
  if (!Array.isArray(answers) || answers.length !== ABILITY_QUESTIONS.length) throw new Error('能力健檢需要 14 個作答');
  const pts = answers.map((a, i) => {
    const o = ABILITY_QUESTIONS[i].opts[a];
    if (!o) throw new Error(`第 ${i + 1} 題作答無效`);
    return o.s;
  });
  const scores = {}, peak = {};
  ABILITIES.forEach((k) => {
    const [a, b] = ABILITY_QS[k];
    scores[k] = pts[a - 1] + pts[b - 1];
    peak[k] = Math.max(pts[a - 1], pts[b - 1]);
  });
  const total = pts.reduce((s, x) => s + x, 0);
  const stage = STAGES.find((s) => total >= s.min && total <= s.max);
  const allSame = ABILITIES.every((k) => scores[k] === scores[ABILITIES[0]]);
  let top = null, low = null;
  if (!allSame) {
    /* 最強：分數高 → 單題最高分高 → 能力順序前者 */
    top = ABILITIES.slice().sort((x, y) => scores[y] - scores[x] || peak[y] - peak[x] || ABILITIES.indexOf(x) - ABILITIES.indexOf(y))[0];
    /* 最需補強：分數低 → 單題最高分低 → 能力順序前者 */
    low = ABILITIES.slice().sort((x, y) => scores[x] - scores[y] || peak[x] - peak[y] || ABILITIES.indexOf(x) - ABILITIES.indexOf(y))[0];
  }
  return { scores, total, stage, top, low, allSame };
}

