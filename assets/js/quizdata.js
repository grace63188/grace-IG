/** answers：12 個選項索引（0–1）→ 計分結果 */
export function scoreCareer(answers) {
  if (!Array.isArray(answers) || answers.length !== CAREER_QUESTIONS.length) throw new Error('職涯定位需要 12 個作答');
  const counts = {}, late = {};
  ROLES.forEach((r) => { counts[r] = 0; late[r] = 0; });
  answers.forEach((a, i) => {
    const o = CAREER_QUESTIONS[i].opts[a];
    if (!o) throw new Error(`第 ${i + 1} 題作答無效`);
    counts[o.r] += 1;
    if (i >= 6) late[o.r] += 1;                    /* Q7–Q12 */
  });
  /* 排名：得分 → Q7–Q12 得分 → R I A S E C 順序 */
  const rank = ROLES.slice().sort((x, y) => counts[y] - counts[x] || late[y] - late[x] || ROLES.indexOf(x) - ROLES.indexOf(y));
  return { counts, late, primary: rank[0], secondary: rank[1], rank };
}

